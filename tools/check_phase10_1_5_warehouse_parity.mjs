#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const warehouse = read('src/economy/warehouse.ts');
const ticker = read('src/economy/ticker.ts');
const game = read('src/core/game.ts');
const ui = read('src/ui/app.ts');
const tests = read('tests/warehouse.test.ts');
const switchingTests = read('tests/phase10_1_5_warehouse_parity.test.ts');
const notes = read('PHASE_10.1.5_NOTES.md');
const fixture = JSON.parse(read('fixtures/warehouse_curve_v0.0.41.json'));
assert.equal(fixture.rows[0].Vi, 10);
assert.equal(fixture.rows[10].Vi, 60);
assert.match(warehouse, /return rt\.explored\.size \* this\.tonsPerCell\(\)/);
assert.match(warehouse, /PLANET_STORAGE_RESOURCES\.reduce/);
assert.match(warehouse, /limitIncomeDelta\(/);
assert.match(ticker, /limitIncomeDelta\?\.\(rawDelta\)/);
assert.match(game, /limitIncomeDelta: \(delta\) => this\.warehouse\.limitIncomeDelta/);
assert.match(game, /storageCapacity: active \? this\.warehouse\.capacityFor\(active\)/);
assert.match(ui, /Планетарный склад/);
assert.doesNotMatch(ui, /<h2>🚚 Межпланетная логистика/);
assert.match(tests, /Ey counts only planet-local resources/);
assert.match(tests, /production is clipped at remaining weighted capacity/);
assert.match(switchingTests, /capacity and used mass follow the active planet-local stock/);
assert.match(notes, /On\(\)\/yy\(\)/);
console.log('Phase 10.1.5 warehouse parity check PASSED');
console.log('- V1 Vi/Hf/Ey warehouse formulas and weights anchored to warehouse_curve_v0.0.41.json');
console.log('- Planet-local stock transfer is the V1 active-planet swap; cargo/depot UI and freight surcharge removed');
console.log('- Production is constrained by active planet warehouse capacity without deleting legacy stock');
