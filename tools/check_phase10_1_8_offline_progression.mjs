#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const game = read('src/core/game.ts');
const saves = read('src/persistence/saveManager.ts');
const production = read('src/economy/production.ts');
const reactor = read('src/crafting/reactor.ts');
const synth = read('src/economy/synth.ts');
const tests = read('tests/phase10_1_8_offline_progression.test.ts');
const registry = JSON.parse(read('src/config/data/balance/v0.0.41/registry.json'));
assert.match(saves, /this\.source\.applyState\(parsed, offlineElapsedMs\)/);
assert.match(saves, /this\.save\(\);\s*this\.deps\.bus\.emit\('game:loaded'/);
assert.match(saves, /this\.source\.applyState\(parsed, 0\)/);
assert.match(game, /Math\.min\(elapsedMs, cfg\.maxSeconds \* 1000\)/);
assert.match(game, /cfg\.minSeconds \* 1000/);
assert.match(game, /nextOfflineBoundaryMs/);
assert.match(game, /tickOfflineInterval/);
assert.match(game, /synthService\.tickOffline\(planets/);
assert.match(synth, /offlineCapMult/);
assert.match(synth, /tickOffline\(planets/);
assert.match(game, /reactorOfflineCapSec/);
assert.match(production, /nextOfflineBoundaryMs/);
assert.match(production, /cooldownUntil = depletionAt \+ this\.cooldownMs\(st\)/);
assert.match(reactor, /tickOfflineSegment/);
assert.match(reactor, /this\.lastMs = gameMs/);
assert.equal(registry.offline.maxSeconds, 43200);
assert.equal(registry.offline.efficiency, 0.5);
assert.equal(registry.offline.minSeconds, 60);
assert.equal(registry.craft.offlineCapSec, 28800);
assert.match(tests, /applies capped offline reactor progress once/);
assert.match(tests, /does not credit intervals shorter than the configured minimum/);
assert.match(tests, /without granting pre-import offline time/);
console.log('Phase 10.1.8 offline progression contract check PASSED');
console.log('- Offline elapsed time uses V1 registry cap, efficiency and minimum threshold');
console.log('- Reactor offline progress has its own legacy cap; surge RNG is not replayed');
console.log('- Load re-anchors the save to prevent duplicate offline rewards; explicit import does not accrue offline time');
